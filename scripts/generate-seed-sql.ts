// Generates supabase/seed.sql from data/seed.ts. Run: npm run seed:sql
import fs from "node:fs";
import * as seed from "../data/seed";

const lit = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "true" : "false";
  if (Array.isArray(v)) return v.length ? `array[${v.map(lit).join(",")}]::text[]` : "'{}'::text[]";
  if (typeof v === "object") return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};
function insert(table: string, rows: Record<string, unknown>[], conflict = "id") {
  if (!rows.length) return "";
  const cols = Object.keys(rows[0]);
  const values = rows.map((r) => `(${cols.map((c) => lit(r[c])).join(", ")})`).join(",\n  ");
  return `insert into public.${table} (${cols.join(", ")}) values\n  ${values}\non conflict (${conflict}) do nothing;\n\n`;
}
const designs = seed.designs.map(({ created_at: _c, updated_at: _u, ...d }) => d);
let sql = "-- Generated by scripts/generate-seed-sql.ts — PLACEHOLDER prices, replace before launch.\n\n";
sql += insert("palette_colors", seed.palette as never);
sql += insert("fabrics", seed.fabrics as never);
sql += insert("addon_groups", seed.addonGroups as never);
sql += insert("addon_options", seed.addonOptions as never);
sql += insert("addon_rules", seed.addonRules as never);
sql += insert("size_options", seed.sizes as never);
sql += insert("price_settings", [{ id: 1, data: seed.settings }]);
sql += insert("designs", designs as never);
sql += insert("design_regions", seed.designRegions as never);
sql += insert("design_layers", seed.designLayers as never);
fs.writeFileSync("supabase/seed.sql", sql);
console.log("wrote supabase/seed.sql");
